'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {app,dialog}=require('electron');
const option=n=>process.argv.find(a=>a.startsWith('--'+n+'='))?.slice(n.length+3),wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
const checks=[],record=(name,pass)=>{assert(pass,name);checks.push(name);};
setTimeout(()=>app.exit(2),150000).unref();
async function run(){
 const project=path.join(option('fixtures'),'Consolidation review'),artifacts=option('artifacts');
 fs.mkdirSync(path.join(project,'docs'),{recursive:true});fs.mkdirSync(artifacts,{recursive:true});
 const source=path.join(project,'docs','decision.md');fs.writeFileSync(source,'# Recorded decision\nThe team chose PostgreSQL for durable data.\n');
 const panel=await require(path.join(option('build'),'panel-app.cjs')).start(),web=panel.window.webContents;
 const js=script=>web.executeJavaScript(script,true),until=async predicate=>{for(let i=0;i<120&&!predicate();i++)await wait(50);assert(predicate());};
 dialog.showOpenDialog=async()=>({canceled:false,filePaths:[project]});
 await js('window.panel.chooseProject()');await js('window.panel.preferences({tab:"Memory"})');panel.show();
 await js(`window.panel.knowledge('configure',${JSON.stringify({scopes:['project'],automatic:false,worker:false,retention:'none',embedding:''})})`);
 await js("window.panel.knowledge('sync')");
 await js("window.panel.knowledge('consolidation-view')");
 record('existing archive explicitly requires migration',panel.store.value.knowledgeConsolidation.schema===1);
 const backup=path.join(artifacts,'before-consolidation.ccmemory');
 fs.writeFileSync(backup,'PRESERVED_BACKUP');
 dialog.showSaveDialog=async()=>({canceled:false,filePath:backup});
 await js('window.panel.knowledgeMigrate().catch(error=>error.message)');
 record('existing backup path is preserved and migration does not start',fs.readFileSync(backup,'utf8')==='PRESERVED_BACKUP'&&panel.store.value.knowledgeConsolidation.schema===1);
 fs.unlinkSync(backup);
 const other=path.join(option('fixtures'),'Other project');fs.mkdirSync(other,{recursive:true});
 let releasePicker;dialog.showSaveDialog=()=>new Promise(resolve=>{releasePicker=resolve;});
 const waiting=js('window.panel.knowledgeMigrate()');await until(()=>!!releasePicker);
 dialog.showOpenDialog=async()=>({canceled:false,filePaths:[other]});await js('window.panel.chooseProject()');
 releasePicker({canceled:false,filePath:backup});await waiting;
 record('project switch during native picker does not migrate or save old project',!fs.existsSync(backup));
 dialog.showOpenDialog=async()=>({canceled:false,filePaths:[project]});await js('window.panel.chooseProject()');
 await js("window.panel.knowledge('consolidation-view')");
 dialog.showSaveDialog=async()=>({canceled:false,filePath:backup});
 await js('window.panel.knowledgeMigrate()');
 await js("window.panel.knowledge('consolidation-view')");
 record('native migration creates external backup and schema 3 view',fs.existsSync(backup)&&panel.store.value.knowledgeConsolidation?.schema===3);
 await js("window.panel.knowledge('consolidation-create',{title:'Review durable data decision'})");
 const prepared=panel.store.value.knowledgeConsolidation,job=prepared.job?.id,cite=prepared.sources.find(c=>c.excerpt.includes('PostgreSQL'));
 record('job pins a source excerpt without generating prose',!!job&&!!cite&&prepared.job.proposals.length===0);
 const proposal={job,page_type:'overview',key:'durable-data',title:'Durable data',body:'The recorded choice is PostgreSQL [S1].',kind:'decision_summary',reason:'Summarize the recorded decision',citations:[cite]};
 await js(`window.panel.knowledge('consolidation-propose',${JSON.stringify(proposal)})`);
 const pending=panel.store.value.knowledgeConsolidation.job.proposals.at(-1);
 record('proposal remains pending and eligible',pending.status==='pending'&&pending.eligible);
 await js(`Array.from(document.querySelectorAll('[aria-label="Knowledge views"] button')).find(b=>b.textContent==='Consolidation').click()`);
 await until(()=>!panel.store.value.knowledgeBusy&&panel.store.value.knowledgeConsolidation?.job?.id===job);
 await js(`document.querySelector('[aria-label="Memory consolidation"] section.cw-record input[type="checkbox"]').click()`);
 await wait(50);
 await js(`Array.from(document.querySelectorAll('[aria-label="Memory consolidation"] button')).find(b=>b.textContent.startsWith('Accept selected')).click()`);
 await until(()=>!panel.store.value.knowledgeBusy&&!!panel.store.value.knowledgeConsolidation?.job?.receipt?.patches?.length);
 record('acceptance has a publication receipt',!!panel.store.value.knowledgeConsolidation.job.receipt?.patches?.length);
 await js("window.panel.knowledge('page','wiki:review:overview')");
 record('accepted text appears in reviewed page',panel.store.value.knowledgePage.body.includes(proposal.body));
 await js(`window.panel.knowledge('consolidation-propose',${JSON.stringify({...proposal,key:'rejected-choice',title:'Rejected choice'})})`);
 const toReject=panel.store.value.knowledgeConsolidation.job.proposals.at(-1);
 await js(`Array.from(document.querySelectorAll('[aria-label="Memory consolidation"] section.cw-record input[type="checkbox"]')).find(e=>!e.disabled).click()`);
 await wait(50);
 await js(`Array.from(document.querySelectorAll('[aria-label="Memory consolidation"] button')).find(b=>b.textContent.startsWith('Reject selected')).click()`);
 await until(()=>!panel.store.value.knowledgeBusy&&panel.store.value.knowledgeConsolidation?.job?.proposals.at(-1)?.status==='rejected');
 record('rejection does not publish',panel.store.value.knowledgeConsolidation.job.proposals.at(-1).status==='rejected');
 await js("window.panel.knowledge('page','wiki:review:overview')");
 const beforeGeneration=panel.store.value.knowledge.generation;
 fs.writeFileSync(source,'# Recorded decision\nThe durable data choice is under review.\n');
 await js(`window.panel.knowledge('consolidation-propose',${JSON.stringify({...proposal,key:'stale-choice',title:'Stale choice'})})`);
 record('failed post-reconcile proposal clears cached page and preserves error',panel.store.value.knowledgeError==='consolidation_context_changed'&&panel.store.value.knowledgePage===null&&panel.store.value.knowledge.generation>beforeGeneration&&panel.store.value.knowledgeConsolidation.job.stale);
 await js("window.panel.knowledge('sync')");await js(`window.panel.knowledge('consolidation-view',{job:${JSON.stringify(job)}})`);
 record('changed source marks job stale',panel.store.value.knowledgeConsolidation.job.stale);
 panel.window.setContentSize(640,920);web.setZoomFactor(2);await wait(200);
 await js(`Array.from(document.querySelectorAll('[aria-label="Knowledge views"] button')).find(b=>b.textContent==='Consolidation').click()`);
 await until(()=>!panel.store.value.knowledgeBusy);
 record('consolidation view fits 320 CSS pixels',await js('innerWidth===320&&document.documentElement.scrollWidth===320'));
 await js(`document.querySelector('[aria-label="Memory consolidation"]').scrollIntoView({block:'start',behavior:'instant'})`);await wait(200);
 fs.writeFileSync(path.join(artifacts,'consolidation.png'),(await web.capturePage()).toPNG());
 fs.writeFileSync(path.join(artifacts,'result.json'),JSON.stringify({passed:true,checks},null,2));app.exit(0);
}
run().catch(error=>{fs.writeFileSync(path.join(option('artifacts'),'result.json'),JSON.stringify({passed:false,checks,error:String(error.stack)},null,2));app.exit(1);});
